const assert=require('node:assert/strict');const {SM,state,pair}=require('./v5-harness')();const C=SM.seatingConstraints;
let s=state(2,1,3);pair(s,1,2);
assert.equal(C.validateAssignment(s,{'0-0':1,'0-1':2,'0-2':null}).valid,false);
assert.equal(C.validateAssignment(s,{'0-0':1,'0-1':null,'0-2':2}).valid,true);
s=state(2,2,2);pair(s,1,2);assert.equal(C.validateAssignment(s,{'0-0':1,'1-1':2}).valid,false,'diagonal counts');
s=state(2,1,3);s.seats[1].type='aisle';pair(s,1,2);assert.equal(C.validateAssignment(s,{'0-0':1,'0-2':2}).valid,true);
s.config.seatExcludedNumbers='2';assert.equal(C.activeRules(s).length,0,'no-seat partner keeps the rule but does not constrain physical seating');
const created=SM.roomLayout.createTemplate(state(8,2,4),'round');
s={...state(8,2,4),...created};pair(s,1,2);const ids=s.seats.map(seat=>seat.id);
assert.equal(C.validateAssignment(s,{[ids[0]]:1,[ids[1]]:2},{partial:true}).valid,false,'free adjacency unconfirmed');
s.seatTopology={confirmed:true,signature:C.signature(s),edges:C.suggest(s)};
assert.equal(C.topology(s).confirmed,true);
assert.equal(C.suggest(s).some(edge=>edge.includes(s.roomLayout.tables[0].seatIds[0])&&edge.includes(s.roomLayout.tables[0].seatIds.at(-1))),true,'round first/last neighbors');
s.roomLayout.zoom=1.3;assert.equal(C.topology(s).confirmed,true,'zoom does not change topology');
s.roomLayout.tables[0].rotation+=15;assert.equal(C.topology(s).confirmed,false,'geometry requires reconfirmation');
s.seatingConstraints.pairs[0].relations=['notSameTable'];
assert.equal(C.validateAssignment(s,{[s.roomLayout.tables[0].seatIds[0]]:1,[s.roomLayout.tables[1].seatIds[0]]:2},{partial:true}).valid,true);
assert.equal(C.validateAssignment(s,{[s.roomLayout.tables[0].seatIds[0]]:1,[s.roomLayout.tables[0].seatIds[1]]:2},{partial:true}).valid,false);
console.log('seating constraints: eight directions, aisles, tables, adjacency and geometry invalidation passed');
